const PAIRS = { '「': '」', '『': '』', '（': '）', '【': '】', '〔': '〕', '(': ')' };
const OPENER = Object.fromEntries(Object.entries(PAIRS).map(([o, c]) => [c, o]));

export function check(text, opts = {}) {
  const cats = { ...DEFAULT_CATS, ...(opts.cats || {}) };
  const maxLen = opts.maxLen || 120;
  const excludeDialogue = opts.excludeDialogue !== false;
  const ignore = opts.ignore || new Set();
  const n = text.length;

  // ルビの読み・会話文・見出し行の位置
  const ruby = new Uint8Array(n + 1);
  const dialogue = new Uint8Array(n + 1);
  const heading = new Uint8Array(n + 1);
  for (const m of text.matchAll(/《[^》\n]*》/g)) ruby.fill(1, m.index, m.index + m[0].length);
  for (const m of text.matchAll(/^#{1,6}[ 　].*$/gm)) heading.fill(1, m.index, m.index + m[0].length);
  let depth = 0;
  for (let i = 0; i < n; i++) {
    const c = text[i];
    if (c === '\n') { depth = 0; continue; }
    if (c === '「' || c === '『') depth++;
    if (depth > 0) dialogue[i] = 1;
    if ((c === '」' || c === '』') && depth > 0) depth--;
  }

  const found = [];
  const add = (start, end, cat, rule, msg, sugg = [], sel = null) => {
    if (!cats[cat] || end <= start || ruby[start]) return;
    if (heading[start] && (cat === 'saho' || cat === 'read')) return;
    if (excludeDialogue && dialogue[start] && (cat === 'style' || cat === 'iinuki' || cat === 'read')) return;
    const t = text.slice(start, end);
    if (ignore.has(`${rule}|${t}`)) return;
    found.push({ start, end, cat, rule, msg, sugg, sel, text: t });
  };

  for (const [cat, list] of [['error', ERROR_PHRASES], ['style', STYLE_PHRASES], ['hyouki', HYOUKI_PHRASES]]) {
    if (!cats[cat]) continue;
    for (const [bad, good, msg] of list) {
      for (let i = text.indexOf(bad); i >= 0; i = text.indexOf(bad, i + bad.length)) {
        add(i, i + bad.length, cat, `phrase:${bad}`, msg, good.split('|'));
      }
    }
  }

  for (const [cat, rule, re, msg, fix] of REGEX_RULES) {
    if (!cats[cat]) continue;
    for (const m of text.matchAll(re)) {
      if (!m[0]) continue;
      add(m.index, m.index + m[0].length, cat, rule, msg, fix ? [fix(m)] : []);
    }
  }

  if (cats.error) checkBrackets(text, add);
  if (cats.yure) checkYure(text, add);
  if (cats.saho) checkIndent(text, add);
  if (cats.read) checkReadability(text, add, maxLen);

  // 重なった指摘は、重要な分類を優先して1つにする
  found.sort((a, b) => RANK[a.cat] - RANK[b.cat] || a.start - b.start || (a.end - a.start) - (b.end - b.start));
  const taken = new Uint8Array(n + 1);
  const result = [];
  for (const is of found) {
    let free = true;
    for (let i = is.start; i < is.end; i++) if (taken[i]) { free = false; break; }
    if (!free) continue;
    taken.fill(1, is.start, is.end);
    result.push(is);
  }
  return result.sort((a, b) => a.start - b.start);
}

function checkBrackets(text, add) {
  let pos = 0;
  for (const line of text.split('\n')) {
    const stack = [];
    for (let i = 0; i < line.length; i++) {
      const c = line[i];
      if (PAIRS[c]) stack.push([c, i]);
      else if (OPENER[c]) {
        if (stack.length && stack[stack.length - 1][0] === OPENER[c]) stack.pop();
        else add(pos + i, pos + i + 1, 'error', 'bracket-close', `対応する「${OPENER[c]}」がありません`);
      }
    }
    for (const [c, i] of stack) add(pos + i, pos + i + 1, 'error', 'bracket-open', `「${c}」が閉じられていません（${PAIRS[c]}）`);
    pos += line.length + 1;
  }
}

function checkYure(text, add) {
  const groups = YURE.map(([name, ...variants]) => [name, variants.map(([label, re]) => [label, [...text.matchAll(re)]])]);

  // カタカナ語の長音のゆれ（サーバ／サーバー）
  const kata = new Map();
  for (const m of text.matchAll(/(?<![ァ-ヺー])[ァ-ヺ][ァ-ヺー]{2,}(?![ァ-ヺー])/g)) kata.set(m[0], (kata.get(m[0]) || 0) + 1);
  for (const w of kata.keys()) {
    if (w.endsWith('ー') || !kata.has(`${w}ー`)) continue;
    const re = (s) => new RegExp(`(?<![ァ-ヺー])${s}(?![ァ-ヺー])`, 'g');
    groups.push([w, [[w, [...text.matchAll(re(w))]], [`${w}ー`, [...text.matchAll(re(`${w}ー`))]]]]);
  }
  // 数字の全角／半角
  groups.push(['数字', [['半角数字', [...text.matchAll(/[0-9]+/g)]], ['全角数字', [...text.matchAll(/[０-９]+/g)]]]]);

  for (const [name, variants] of groups) {
    const used = variants.filter(([, ms]) => ms.length);
    if (used.length < 2) continue;
    const major = used.reduce((a, b) => (b[1].length > a[1].length || (b[1].length === a[1].length && b[1][0].index < a[1][0].index) ? b : a));
    for (const [label, ms] of used) {
      if (label === major[0]) continue;
      for (const m of ms) {
        const sugg = name === '数字'
          ? [label === '半角数字' ? m[0].replace(/[0-9]/g, (d) => String.fromCharCode(d.charCodeAt(0) + 0xFEE0)) : m[0].normalize('NFKC')]
          : [major[0]];
        add(m.index, m.index + m[0].length, 'yure', `yure:${name}`,
          `表記ゆれ：「${label}」${ms.length}回と「${major[0]}」${major[1].length}回が混在しています`, sugg);
      }
    }
  }
}

function checkIndent(text, add) {
  const lines = [];
  let pos = 0;
  for (const line of text.split('\n')) { lines.push([pos, line]); pos += line.length + 1; }
  const isBreak = (l) => /^[＊*◇◆□■○●☆★・\-－—―\s　]+$/.test(l);
  const narrative = lines.filter(([, l]) => l.trim() && !isBreak(l) && !/^#{1,6}[ 　]/.test(l) && !/^[　 ]*[「『（(【〔―…＜<]/.test(l));
  const indented = narrative.filter(([, l]) => l.startsWith('　')).length;
  if (narrative.length >= 3 && indented / narrative.length >= 0.5) {
    for (const [p, l] of narrative) {
      if (l.startsWith('　') || l.startsWith(' ')) continue;
      const first = [...l][0];
      add(p, p + first.length, 'saho', 'indent', '段落の頭に字下げ（全角空白）がありません', [`　${first}`]);
    }
  }
  const dialogue = lines.filter(([, l]) => /^[　 ]*[「『]/.test(l));
  const dlgIndented = dialogue.filter(([, l]) => /^[　 ]+[「『]/.test(l));
  if (dialogue.length >= 3 && dlgIndented.length / dialogue.length < 0.5) {
    for (const [p, l] of dlgIndented) {
      const k = l.search(/[「『]/);
      add(p, p + k, 'saho', 'indent-dialogue', '会話文の「の前は字下げしないのが一般的です', ['']);
    }
  }
}

function checkReadability(text, add, maxLen) {
  for (const m of text.matchAll(/[^。！？!?\n]+[。！？!?」』]*/g)) {
    const body = m[0];
    const s = m.index;
    const e = s + body.length;
    const len = [...body.trim()].length;
    if (len > maxLen) add(e - 1, e, 'read', 'long', `この文は${len}字あります（目安 ${maxLen}字）`, [], [s, e]);
    const commas = [...body.matchAll(/[、，]/g)];
    if (commas.length >= 5) {
      const at = s + commas[4].index;
      add(at, at + 1, 'read', 'commas', `読点が${commas.length}個ある文です。文を分けると読みやすくなります`, [], [s, e]);
    }
  }
  for (const m of text.matchAll(/の[^の、。！？「」\n]{1,6}の[^の、。！？「」\n]{1,6}の/g)) {
    add(m.index, m.index + m[0].length, 'read', 'no-chain', '「の」が3回続いています');
  }
}
